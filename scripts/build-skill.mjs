// Bundles packages/cli into the standalone, dependency-free skill script.
// Usage: node scripts/build-skill.mjs [--check]
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const outfile = fileURLToPath(
  new URL('../skills/shortcuts-doctor/scripts/inspect-shortcut.mjs', import.meta.url)
);
const checkOnly = process.argv.includes('--check');

const result = await build({
  entryPoints: [fileURLToPath(new URL('../packages/cli/src/index.ts', import.meta.url))],
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  legalComments: 'none',
  banner: {
    js: '// GENERATED by scripts/build-skill.mjs — do not edit. Source: packages/core, packages/cli.',
  },
  outfile,
  write: !checkOnly,
});

if (checkOnly) {
  const [output] = result.outputFiles ?? [];
  if (!output) throw new Error('esbuild produced no output.');
  if (readFileSync(outfile, 'utf8') !== output.text) {
    process.stderr.write('Skill bundle is stale. Run `pnpm build:skill` and commit the result.\n');
    process.exitCode = 1;
  }
}
